'use strict';

function script() {
  return [
    'param([switch]$Silent)',
    "$ErrorActionPreference = 'SilentlyContinue'",
    "$app = Join-Path $env:LOCALAPPDATA 'Programs\\ZapretMini'",
    "$localData = Join-Path $env:LOCALAPPDATA 'ZapretMini'",
    "$roaming = Join-Path $env:APPDATA 'ZapretMini'",
    "$desktop = [Environment]::GetFolderPath('Desktop')",
    "$task = 'ZapretMini'",
    "$reg = 'HKCU:\\Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\ZapretMini'",
    "$identity = [Security.Principal.WindowsIdentity]::GetCurrent()",
    "$principal = New-Object Security.Principal.WindowsPrincipal($identity)",
    "$isAdmin = $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)",
    'if (-not $isAdmin) {',
    "  $args = @('-NoProfile','-ExecutionPolicy','Bypass','-File', ('\"' + $PSCommandPath + '\"'))",
    "  if ($Silent) { $args += '-Silent' }",
    "  Start-Process -FilePath 'powershell.exe' -Verb RunAs -ArgumentList $args",
    '  exit',
    '}',
    'if (-not $Silent) {',
    '  Add-Type -AssemblyName System.Windows.Forms',
    "  $text = 'Удалить Zapret Mini?' + [Environment]::NewLine + [Environment]::NewLine + 'Будут удалены приложение, настройки, список сайтов и управляемая папка zapret.' + [Environment]::NewLine + 'Папка zapret, выбранная вручную вне %LOCALAPPDATA%\\ZapretMini, останется.'",
    "  $answer = [System.Windows.Forms.MessageBox]::Show($text, 'Zapret Mini', [System.Windows.Forms.MessageBoxButtons]::YesNo, [System.Windows.Forms.MessageBoxIcon]::Warning)",
    '  if ($answer -ne [System.Windows.Forms.DialogResult]::Yes) { exit }',
    '}',
    "& \"$env:SystemRoot\\System32\\schtasks.exe\" /End /TN $task 2>$null | Out-Null",
    "& \"$env:SystemRoot\\System32\\schtasks.exe\" /Delete /TN $task /F 2>$null | Out-Null",
    'Get-Process ZapretMini,winws -ErrorAction SilentlyContinue | Stop-Process -Force',
    'for ($i = 0; $i -lt 40; $i++) {',
    '  if (-not (Get-Process ZapretMini,winws -ErrorAction SilentlyContinue)) { break }',
    '  Start-Sleep -Milliseconds 500',
    '}',
    "& \"$env:SystemRoot\\System32\\sc.exe\" stop zapret 2>$null | Out-Null",
    "& \"$env:SystemRoot\\System32\\sc.exe\" delete zapret 2>$null | Out-Null",
    "& \"$env:SystemRoot\\System32\\sc.exe\" stop WinDivert 2>$null | Out-Null",
    "& \"$env:SystemRoot\\System32\\sc.exe\" delete WinDivert 2>$null | Out-Null",
    "$manifest = Join-Path $roaming 'user-sites.json'",
    '$hostnames = @()',
    'if (Test-Path $manifest) {',
    '  try {',
    '    $json = Get-Content $manifest -Raw | ConvertFrom-Json',
    '    foreach ($site in $json.sites) { foreach ($name in $site.hostnames) { if ($name) { $hostnames += [string]$name } } }',
    '  } catch { }',
    '}',
    "$hosts = Join-Path $env:SystemRoot 'System32\\drivers\\etc\\hosts'",
    'if ((Test-Path $hosts) -and $hostnames.Count -gt 0) {',
    '  $lines = Get-Content $hosts',
    '  $out = @()',
    '  foreach ($line in $lines) {',
    '    $clean = $line.Trim()',
    "    if (-not $clean -or $clean.StartsWith('#')) { $out += $line; continue }",
    "    $parts = $clean -split '\\s+'",
    '    if ($parts.Count -lt 2) { $out += $line; continue }',
    "    $hostName = ($parts[1..($parts.Count - 1)] -join ' ').ToLower()",
    '    $skip = $false',
    '    foreach ($name in $hostnames) {',
    '      $n = ([string]$name).ToLower()',
    "      if ($hostName -eq $n -or $hostName.EndsWith('.' + $n)) { $skip = $true; break }",
    '    }',
    '    if (-not $skip) { $out += $line }',
    '  }',
    "  Copy-Item $hosts ($hosts + '.bak-zapretmini-uninstall') -Force",
    '  Set-Content -Path $hosts -Value $out -Encoding ASCII',
    '}',
    "Remove-Item (Join-Path $desktop 'Zapret Mini.lnk') -Force",
    'Remove-Item -Path $reg -Recurse -Force',
    'for ($i = 0; $i -lt 60; $i++) {',
    '  Remove-Item $app -Recurse -Force -ErrorAction SilentlyContinue',
    '  if (-not (Test-Path $app)) { break }',
    '  Start-Sleep -Milliseconds 500',
    '}',
    "$cleanup = Join-Path $env:TEMP ('zapretmini-cleanup-' + $PID + '.ps1')",
    '$cleanupText = @"',
    'Start-Sleep -Seconds 2',
    'for (`$i = 0; `$i -lt 60; `$i++) {',
    "  Remove-Item '$app' -Recurse -Force -ErrorAction SilentlyContinue",
    "  if (-not (Test-Path '$app')) { break }",
    '  Start-Sleep -Milliseconds 500',
    '}',
    "Remove-Item '$localData' -Recurse -Force -ErrorAction SilentlyContinue",
    "Remove-Item '$roaming' -Recurse -Force -ErrorAction SilentlyContinue",
    "Remove-Item '$cleanup' -Force -ErrorAction SilentlyContinue",
    '"@',
    'Set-Content -Path $cleanup -Value $cleanupText -Encoding UTF8',
    "Start-Process -FilePath 'powershell.exe' -WindowStyle Hidden -ArgumentList @('-NoProfile','-ExecutionPolicy','Bypass','-File', $cleanup)",
    'exit'
  ].join('\r\n');
}

module.exports = { script };
